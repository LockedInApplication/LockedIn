import { randomUUID } from "node:crypto";
import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";
import { connectionFixtures } from "./discovery-connection.fixtures.js";
vi.mock("../../../lib/email.js",()=>({sendEmail:async()=>{},sendPasswordResetEmail:async()=>{}}));
vi.mock("../../journey-notifications/journey-email.service.js",()=>({sendJourneyEmailSafely:async()=>{}}));
describe.skipIf(process.env.DISCOVERY_INTEGRATION!=="true")("isolated discovery notification occurrences",()=>{
  let server:Awaited<ReturnType<typeof import("../../../app.js").buildServer>>,f:ReturnType<typeof connectionFixtures>;
  const oldEnv={...process.env};
  beforeAll(async()=>{server=await(await import("../../../app.js")).buildServer();await server.listen({port:0,host:"127.0.0.1"});f=connectionFixtures(server);});
  afterAll(async()=>{process.env=oldEnv;await server?.close();await(await import("../../../lib/prisma.js")).prisma.$disconnect();});
  it("creates recipient-owned deduplicated tasks and fingerprints shared changes but not partner drafts",async()=>{
    const {prisma}=await import("../../../lib/prisma.js");
    const {listNotifications,notificationFingerprint,markNotificationRead}=await import("../../notifications/notification.repository.js");
    const a=await f.person(),b=await f.person(),c=await f.person(),key=randomUUID(),sent=await f.send(a,b,key);expect(sent.statusCode).toBe(200);const id=sent.json().value.id,url=`/api/discovery/connections/${id}`;
    const inbox=await listNotifications(b.id);expect(inbox.unreadCount).toBe(1);expect(inbox.items[0]).toMatchObject({kind:"DISCOVERY_INVITED",view:"discovery",entityId:id});
    await expect(prisma.notification.create({data:{recipientId:b.id,kind:"DISCOVERY_INVITED",entityId:id,eventKey:randomUUID()}})).rejects.toThrow();
    await expect(prisma.notification.create({data:{recipientId:b.id,relationshipId:"discovery-preserved-relationship",discoveryConnectionId:id,kind:"DISCOVERY_INVITED",entityId:id,eventKey:randomUUID()}})).rejects.toThrow();
    expect(await markNotificationRead(c.id,BigInt(inbox.items[0]!.id))).toBe(false);
    await f.send(a,b,key);expect(await prisma.notification.count({where:{recipientId:b.id}})).toBe(1);
    await f.request(b,"POST",`${url}/accept`,{});await f.request(b,"POST",`${url}/accept`,{});
    expect(await prisma.notification.count({where:{recipientId:a.id,kind:"DISCOVERY_ACCEPTED"}})).toBe(1);
    const fingerprint=await notificationFingerprint(b.id);
    expect((await f.request(a,"PUT",`${url}/draft`,{text:"SECRET DRAFT",revision:0})).statusCode).toBe(404);
    expect(await notificationFingerprint(b.id)).toBe(fingerprint);
    const share={draftRevision:1,requestId:randomUUID()};
    expect((await f.request(a,"POST",`${url}/share`,share)).statusCode).toBe(404);
    expect(await notificationFingerprint(b.id)).toBe(fingerprint);
    expect(await prisma.notification.count({where:{recipientId:b.id,kind:"DISCOVERY_RESPONSE_SHARED"}})).toBe(0);
    expect(JSON.stringify(await listNotifications(b.id))).not.toMatch(/SECRET DRAFT|PRIVATE AUTH NAME|@example/);
    const beforeClose=await notificationFingerprint(b.id),count=await prisma.notification.count({where:{recipientId:b.id}});
    await f.request(a,"POST",`${url}/close`,{});
    expect(await notificationFingerprint(b.id)).not.toBe(beforeClose);
    expect(await prisma.notification.count({where:{recipientId:b.id}})).toBe(count);
    expect((await listNotifications(b.id)).unreadCount).toBe(0);
  });
  it("honors suppression without backfill and still publishes quiet committed invalidation",async()=>{
    const {prisma}=await import("../../../lib/prisma.js");
    const {listNotifications,notificationFingerprint}=await import("../../notifications/notification.repository.js");
    const {notificationBroker}=await import("../../notifications/notification.broker.js");
    const a=await f.person(),b=await f.person();await prisma.user.update({where:{id:b.id},data:{inAppActivity:false}});
    const events:boolean[]=[],unsubscribe=notificationBroker.subscribe(b.id,activity=>events.push(activity));
    const fingerprint=await notificationFingerprint(b.id),key=randomUUID(),sent=await f.send(a,b,key);expect(sent.statusCode).toBe(200);
    expect(events).toContain(false);expect(events).not.toContain(true);expect(await notificationFingerprint(b.id)).not.toBe(fingerprint);
    expect((await listNotifications(b.id)).items).toEqual([]);
    await prisma.user.update({where:{id:b.id},data:{inAppActivity:true}});
    await f.send(a,b,key);expect((await listNotifications(b.id)).items).toEqual([]);
    unsubscribe?.();
  });
  it("deduplicates readiness/promotion and keeps quiet safety actions from creating pressure alerts",async()=>{
    const {prisma}=await import("../../../lib/prisma.js");
    const {listNotifications}=await import("../../notifications/notification.repository.js");
    const a=await f.person(),b=await f.person(),sent=await f.send(a,b);expect(sent.statusCode).toBe(200);const id=sent.json().value.id,url=`/api/discovery/connections/${id}`;
    await f.request(b,"POST",`${url}/accept`,{});
    const ready={ready:true,consentVersion:1,exclusiveConsent:true};
    await f.request(a,"POST",`${url}/readiness`,ready);await f.request(a,"POST",`${url}/readiness`,ready);
    expect(await prisma.notification.count({where:{recipientId:b.id,kind:"DISCOVERY_BUILD_READY"}})).toBe(1);
    await f.request(b,"POST",`${url}/readiness`,ready);await f.request(b,"POST",`${url}/readiness`,ready);
    expect(await prisma.notification.count({where:{discoveryConnectionId:id,kind:"DISCOVERY_PROMOTED"}})).toBe(2);
    const count=await prisma.notification.count({where:{discoveryConnectionId:id}});
    await f.request(b,"POST","/api/discovery/reports",{sourceType:"INVITATION",sourceId:id,reason:"OTHER",requestId:randomUUID()});
    await f.request(b,"POST","/api/discovery/blocks",{connectionId:id});
    expect(await prisma.notification.count({where:{discoveryConnectionId:id}})).toBe(count);
    expect((await listNotifications(b.id)).items.every(item=>!item.message.includes("OTHER"))).toBe(true);
  });
});
